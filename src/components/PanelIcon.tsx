export function PanelIcon({
  name,
  className,
  rainbow = false,
}: {
  name: PanelIconName;
  className?: string;
  rainbow?: boolean;
}) {
  const gradientId = useId();
  if (name === "global-mail-read" || name === "global-mail-unread") {
    return <img src={`/${name}.svg`} alt="" className={className} />;
  }
  const icon = ICONS[name];
  return (
    <svg
      className={className}
      width="24"
      height="24"
      viewBox={icon.viewBox}
      fill={rainbow ? `url(#${gradientId})` : "currentColor"}
      aria-hidden="true"
      focusable="false"
    >
      {rainbow && (
        <defs>
          <linearGradient id={gradientId} x1="0" y1="0" x2="1" y2="1">
            {HUES.map((hue, index) => (
              <stop
                key={hue}
                offset={`${(index / (HUES.length - 1)) * 100}%`}
                stopColor={`hsl(${hue} 85% 62%)`}
              />
            ))}
          </linearGradient>
        </defs>
      )}
      <path d={icon.path} />
    </svg>
  );
}
